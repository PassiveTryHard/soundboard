// Material package provides all of Flutter's core UI components
// like Scaffold, AppBar, BottomNavigationBar, Icons, etc.
import 'package:flutter/material.dart';

// Riverpod is our state management solution — ProviderScope and
// ConsumerWidget come from here
import 'package:flutter_riverpod/flutter_riverpod.dart';

// Hive is our local database — stores SoundButton objects permanently
// on the device between app sessions
import 'package:hive_flutter/hive_flutter.dart';

// Our SoundButton data model and its generated Hive adapter
import 'models/sound_button.dart';

// Our custom dark theme definition
import 'theme/app_theme.dart';

// The two main screens of the app
import 'screens/home_screen.dart';
import 'screens/settings_screen.dart';

// main() is the entry point of the app — exactly like main() in C++
// The 'async' keyword means this function can wait for operations to
// finish before continuing, using the 'await' keyword
void main() async {
  // Ensures Flutter's internal engine is fully ready before we run
  // any setup code. Required whenever you do anything before runApp()
  // such as initializing databases or loading preferences
  WidgetsFlutterBinding.ensureInitialized();

  // Initializes the Hive database and points it at the correct folder
  // on the device's storage. 'await' pauses here until Hive is ready
  await Hive.initFlutter();

  // Registers our SoundButton model with Hive so it knows how to
  // read and write SoundButton objects to disk. The adapter was
  // automatically generated by build_runner in Phase 2
  Hive.registerAdapter(SoundButtonAdapter());

  // Opens the 'sound_buttons' box — think of a box like a database
  // table. This is where all SoundButton objects are stored and
  // retrieved. Must be opened before any code tries to read from it
  await Hive.openBox<SoundButton>('sound_buttons');

  // Launches the app. ProviderScope is required by Riverpod — it
  // wraps the entire app and acts as the container that holds all
  // of our app's state. Nothing Riverpod-related works without it
  runApp(const ProviderScope(child: MyApp()));
}

// MyApp is the root widget of the entire application. Every other
// widget in the app is a child of this one, directly or indirectly.
// ConsumerWidget is Riverpod's version of StatelessWidget — the 'ref'
// parameter it provides lets us read and watch state providers
class MyApp extends ConsumerWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    // MaterialApp sets up core app-wide configuration including the
    // title, theme, and the first screen to display
    return MaterialApp(
      // App name used by the OS in the app switcher
      title: 'Soundboard',

      // Removes the red 'DEBUG' ribbon from the top right corner
      // of the screen during development
      debugShowCheckedModeBanner: false,

      // Applies our custom dark theme defined in app_theme.dart
      // to every screen and widget in the app automatically
      theme: AppTheme.darkTheme,

      // The first screen shown when the app launches
      home: const MainScreen(),
    );
  }
}

// MainScreen manages the bottom navigation bar and switches between
// the Home and Settings screens based on which tab is active.
// StatefulWidget is used here because we need to track and update
// which tab is currently selected — that's mutable state
class MainScreen extends StatefulWidget {
  const MainScreen({super.key});

  // createState() links this widget to its mutable state class below
  @override
  State<MainScreen> createState() => _MainScreenState();
}

// The underscore prefix on _MainScreenState marks it as private —
// it can only be accessed from within this file
class _MainScreenState extends State<MainScreen> {
  // Tracks the index of the currently selected tab
  // 0 = Soundboard (Home), 1 = Settings
  int _currentIndex = 0;

  // The list of screens that correspond to each tab.
  // Using 'const' here means Flutter creates these widgets once
  // and reuses them rather than rebuilding them on every tab switch
  final List<Widget> _screens = const [
    HomeScreen(),
    SettingsScreen(),
  ];

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      // Shows whichever screen matches the current tab index
      body: _screens[_currentIndex],

      // The navigation bar at the bottom of the screen
      bottomNavigationBar: BottomNavigationBar(
        // Tells the bar which tab to highlight as selected
        currentIndex: _currentIndex,

        // Called whenever the user taps a tab.
        // setState() tells Flutter something changed and the widget
        // needs to rebuild — without it the UI wouldn't update
        onTap: (index) => setState(() => _currentIndex = index),

        // The two tabs — each has an icon and a label
        items: const [
          BottomNavigationBarItem(
            icon: Icon(Icons.grid_view_rounded),
            label: 'Soundboard',
          ),
          BottomNavigationBarItem(
            icon: Icon(Icons.settings_rounded),
            label: 'Settings',
          ),
        ],
      ),
    );
  }
}